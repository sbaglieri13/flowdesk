-- Flowdesk database schema.
-- Run once in the Supabase SQL Editor (Dashboard -> SQL Editor -> New query -> paste -> Run).
-- Safe to run again: it only creates what is missing.

create table if not exists columns (
    id integer generated by default as identity primary key,
    name varchar(100) not null,
    icon varchar(40),
    position integer not null default 0,
    is_default boolean not null default false,
    is_hidden boolean not null default false,
    is_done_state boolean not null default false,
    created_at timestamp not null default now(),
    updated_at timestamp not null default now()
);

create table if not exists tags (
    id integer generated by default as identity primary key,
    name varchar(50) not null unique,
    color varchar(20) not null,
    icon varchar(40) not null default 'tag',
    created_at timestamp not null default now()
);

create table if not exists reporters (
    id integer generated by default as identity primary key,
    name varchar(100) not null unique,
    created_at timestamp not null default now()
);

create table if not exists priorities (
    id integer generated by default as identity primary key,
    key varchar(20) unique,
    name varchar(50) not null,
    icon varchar(40) not null default 'minus',
    color varchar(20) not null default '#64748b',
    position integer not null default 0,
    is_default boolean not null default false,
    is_hidden boolean not null default false,
    created_at timestamp not null default now()
);

create table if not exists task_types (
    id integer generated by default as identity primary key,
    key varchar(20) unique,
    name varchar(50) not null,
    icon varchar(40) not null default 'clipboard-text',
    color varchar(20) not null default '#64748b',
    position integer not null default 0,
    is_default boolean not null default false,
    is_hidden boolean not null default false,
    created_at timestamp not null default now()
);

create table if not exists settings (
    key varchar(100) primary key,
    value text
);

create table if not exists tasks (
    id integer generated by default as identity primary key,
    display_code varchar(20) not null unique,
    title varchar(200) not null,
    description text,
    notes text,
    column_id integer not null references columns (id),
    position integer not null default 0,
    priority_id integer not null references priorities (id),
    type_id integer references task_types (id),
    deadline date,
    external_reference varchar(100),
    reporter_id integer references reporters (id),
    created_at timestamp not null default now(),
    updated_at timestamp not null default now(),
    closed_at timestamp
);

create index if not exists tasks_column_position_idx on tasks (column_id, position);
create index if not exists tasks_reporter_idx on tasks (reporter_id);

create table if not exists task_tags (
    task_id integer not null references tasks (id) on delete cascade,
    tag_id integer not null references tags (id) on delete cascade,
    primary key (task_id, tag_id)
);

create index if not exists task_tags_tag_idx on task_tags (tag_id);

create table if not exists task_doc_links (
    id integer generated by default as identity primary key,
    task_id integer not null references tasks (id) on delete cascade,
    url varchar(500) not null,
    position integer not null default 0
);

create index if not exists task_doc_links_task_idx on task_doc_links (task_id);

create table if not exists checklist_items (
    id integer generated by default as identity primary key,
    task_id integer not null references tasks (id) on delete cascade,
    text text not null,
    is_done boolean not null default false,
    position integer not null default 0,
    created_at timestamp not null default now()
);

create index if not exists checklist_items_task_idx on checklist_items (task_id);

create table if not exists attachments (
    id integer generated by default as identity primary key,
    task_id integer not null references tasks (id) on delete cascade,
    filename varchar(255) not null,
    stored_name varchar(64) not null unique,
    content_type varchar(100),
    size_bytes integer not null,
    created_at timestamp not null default now()
);

create index if not exists attachments_task_idx on attachments (task_id);

create table if not exists time_entries (
    id integer generated by default as identity primary key,
    task_id integer not null references tasks (id) on delete cascade,
    hours double precision not null,
    note varchar(200),
    logged_date date not null,
    created_at timestamp not null default now()
);

create index if not exists time_entries_task_idx on time_entries (task_id);

-- Flowdesk talks to the database with the server-side connection string only.
-- Row Level Security without policies makes every table unreachable through the
-- public Supabase API (anon and authenticated keys).
alter table columns enable row level security;
alter table tags enable row level security;
alter table reporters enable row level security;
alter table priorities enable row level security;
alter table task_types enable row level security;
alter table settings enable row level security;
alter table tasks enable row level security;
alter table task_tags enable row level security;
alter table task_doc_links enable row level security;
alter table checklist_items enable row level security;
alter table attachments enable row level security;
alter table time_entries enable row level security;
